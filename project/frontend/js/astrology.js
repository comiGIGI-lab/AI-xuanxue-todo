// 计算太阳星座
export function getSunSign(month, day) {
  for (const sign of SUN_SIGN_DATES) {
    const [startMonth, startDay] = sign.start;
    const [endMonth, endDay] = sign.end;
    if (month === startMonth && day >= startDay) return sign.name;
    if (month === endMonth && day <= endDay) return sign.name;
    if (month > startMonth && month < endMonth) return sign.name;
  }
  return '摩羯座';
}

// 计算月亮星座（简化近似算法）
export function getMoonSign(year, month, day) {
  const baseDate = new Date(2000, 0, 1);
  const targetDate = new Date(year, month - 1, day);
  const daysDiff = Math.floor((targetDate - baseDate) / (1000 * 60 * 60 * 24));
  const moonCycle = 27.3;
  const position = ((daysDiff % moonCycle) + moonCycle) % moonCycle;
  const signIndex = Math.floor(position / (moonCycle / 12));
  return ALL_SIGNS[signIndex % 12];
}

// 月亮可能范围（无时辰时约2个星座）
export function getMoonSignRange(year, month, day) {
  const base = getMoonSign(year, month, day);
  const idx = ALL_SIGNS.indexOf(base);
  const next = ALL_SIGNS[(idx + 1) % 12];
  return [base, next];
}

