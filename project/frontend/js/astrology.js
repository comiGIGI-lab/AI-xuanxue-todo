// 计算行星落位（简化近似）
export function getPlanetSigns(year, month, day) {
  const sunSign = getSunSign(month, day);

  // 水星：离太阳不超过28度
  const mercuryOffset = ((year + month) % 3) - 1;
  const mercurySign = getAdjacentSign(sunSign, mercuryOffset);

  // 金星：离太阳不超过48度
  const venusOffset = ((year + day) % 5) - 2;
  const venusSign = getAdjacentSign(sunSign, venusOffset);

  // 火星：约687天绕黄道一周
  const marsCycle = 687;
  const baseDate = new Date(2000, 0, 1);
  const targetDate = new Date(year, month - 1, day);
  const daysDiff = Math.floor((targetDate - baseDate) / (1000 * 60 * 60 * 24));
  const marsPosition = ((daysDiff % marsCycle) + marsCycle) % marsCycle;
  const marsSignIndex = Math.floor(marsPosition / (marsCycle / 12));
  const marsSign = ALL_SIGNS[marsSignIndex % 12];

  return { mercury: mercurySign, venus: venusSign, mars: marsSign };
}

// 行星可能范围（无时辰时约2-3个星座）
export function getPlanetSignRange(sunSign, planetName, year) {
  const planetSigns = getPlanetSigns(year, 1, 1);
  const base = planetSigns[planetName];
  const idx = ALL_SIGNS.indexOf(base);
  return [ALL_SIGNS[(idx - 1 + 12) % 12], base, ALL_SIGNS[(idx + 1) % 12]];
}

function getAdjacentSign(sign, offset) {
  const index = ALL_SIGNS.indexOf(sign);
  const newIndex = ((index + offset) % 12 + 12) % 12;
  return ALL_SIGNS[newIndex];
}

// 获取慢速行星（按年份）
function getSlowPlanet(planet, year) {
  const table = SLOW_PLANETS_BY_YEAR[planet];
  if (!table) return '未知';
  // 找到最接近的年份
  let closestYear = year;
  while (!table[closestYear] && closestYear >= 1900) {
    closestYear--;
  }
  return table[closestYear] || '未知';
}

// 完整星盘计算
export function calculateAstrology(year, month, day) {
  const sunSign = getSunSign(month, day);
  const moonSign = getMoonSign(year, month, day);
  const moonRange = getMoonSignRange(year, month, day);
  const risingSign = getRisingSign(sunSign);
  const risingRange = getRisingSignRange(sunSign);
  const planetSigns = getPlanetSigns(year, month, day);

  const mercuryRange = getPlanetSignRange(sunSign, 'mercury', year);
  const venusRange = getPlanetSignRange(sunSign, 'venus', year);
  const marsRange = getPlanetSignRange(sunSign, 'mars', year);

  // 慢速行星（按年份可确定）
  const jupiter = getSlowPlanet('jupiter', year);
  const saturn = getSlowPlanet('saturn', year);
  const uranus = getSlowPlanet('uranus', year);
  const neptune = getSlowPlanet('neptune', year);
  const pluto = getSlowPlanet('pluto', year);

  return {
    sun: sunSign,
    moon: moonSign,
    moonRange,
    rising: risingSign,
    risingRange,
    mercury: planetSigns.mercury,
    mercuryRange,
    venus: planetSigns.venus,
    venusRange,
    mars: planetSigns.mars,
    marsRange,
    jupiter,
    saturn,
    uranus,
    neptune,
    pluto,
    sunElement: SIGN_ELEMENTS[sunSign],
    moonModality: SIGN_MODALITIES[moonSign],
    planetMeanings: PLANET_MEANINGS
  };
}
